// 评分规则默认文案生成器：根据赛事配置（scoring_rule / ranking_mode）生成 markdown。
// 供创建赛事表单与编辑赛事表单共用；开关"关闭→打开"时重新生成覆盖。
// 文案中的计分描述与后端实际逻辑一一对应：
//   测试点公式 100/(1+log(t/tbest)/log1.5)  → services/Submission.ts calcTimeRatioScore
//   普通题型取平均 / HCCL 求和(functional 15 / performance 满分10 / 其他满分100) → calculateContestProblemScore
//   难度加权与第一名加分 → domain/ScoringRules.ts
//   排名链条（含提交次数少者在前）→ open.js/group.js/contest-screen.js 排序

export function buildDefaultScoringRules(config) {
  const scoringRule = String(config?.scoringRule || 'default');
  const rankingMode = String(config?.rankingMode || 'score');

  const totalScoreSection = scoringRule === 'difficulty_weighted'
    ? `## 三、总分计算

本比赛采用**难度加权**计分：

- 每题加权得分 = 该题原始得分 × 该题难度系数（难度系数范围 1~5）
- **第一名加分**：每道题当前排名第一的参赛者（且该题有得分），额外获得「难度系数 × 10」的加分
- 总分 = 各题加权得分（含第一名加分）之和`
    : `## 三、总分计算

本比赛总分为**各题得分直接相加**：

> 总分 = 题目 1 得分 + 题目 2 得分 + ……`;

  const rankingSection = rankingMode === 'num'
    ? `## 四、排名方式

本比赛按**通过题数**从高到低排名。通过题数相同时，依次比较：总分（高者在前）→ 总提交次数（少者在前）。`
    : `## 四、排名方式

本比赛按**总分**从高到低排名。总分相同时，依次比较：通过题数（多者在前）→ 总提交次数（少者在前）。`;

  return `## 一、单题得分

### 普通题型

每道题目的得分由测试点成绩决定：

- **测试点得分公式**：\`得分 = 100 / (1 + log(你的用时 / 该测试点最优用时) / log(1.5))\`
- **最优用时（TBest）**：每个测试点在所有参赛者提交中的历史最快用时。达到最优用时即得该测试点满分 100 分；用时每放宽 1.5 倍，得分降一档（最优用时 = 100 分、1.5 倍 = 50 分、2.25 倍 ≈ 33.3 分、3.375 倍 = 25 分……）
- **题目得分**：全部测试点得分的**平均值**（保留两位小数）
- 测试点未通过得 0 分。题目是否支持部分得分，可通过提交结果判断：**部分测试点通过且得分大于 0**，说明该题为"部分通过计分"模式；**部分通过但得分为 0**，说明该题为"全部测试点通过才计分"模式

### HCCL 题型（集合通信）

HCCL 题目按测试点类型分别计分，各测试点得分**直接相加**：

| 测试点类型 | 计分方式 |
|-----------|---------|
| 功能测试点（functional） | 通过固定得 15 分，不按时间计分 |
| 性能测试点（performance） | 通过后按用时分档计分，满分 10 分 |
| 其他测试点 | 通过后按用时分档计分，满分 100 分 |

### 关于 TBest 的动态说明

TBest 是全场比赛维度的历史最优：**其他选手更快的提交会刷新 TBest**，因此同一份代码在不同时间评测，得分可能不同（甚至下降）。这是正常的动态计分机制，最终成绩以排行榜为准。

## 二、排行榜代表提交

每道题的排行榜取你哪次提交，由该题目的提交模式决定（以题目页面标注为准）：

- **最新提交模式（latest）**：取你**最后一次**提交的成绩。每次新的提交都会覆盖你在排行榜上的成绩——即使新提交比之前更差，请谨慎提交。
- **最优提交模式（best）**：取你**所有提交中得分最高**的那次成绩。你的排行榜成绩只升不降，可以放心多次尝试优化。

${totalScoreSection}

${rankingSection}
`;
}
