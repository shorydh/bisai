"""Restore the task-specified PL and PL-lazy snapshots; never build or submit."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import shutil
import subprocess
from datetime import datetime, timezone

HERE = Path(__file__).resolve().parent
EXPECTED = {
    'PL': '988e491ec2d8d758adac5caa0e304cc81cb500ade732aadc9427fa1254267d41',
    'PL-lazy': '03e6bc1bb81dc40ba71d4691aeb08feebdf38fe0a2ac12f2a59aeff0445afb39',
}
HEADER = 'op_kernel/pad_v3_grad.h'
EXPECTED_HEADER = '676d61fc35ade7689f96fa8e1cc77c2973aab0820b949607d3480f847edcdcac'
REFERENCE = '1542d63e602aa3aaa60242e91ea0d6a8ac038bab788c6898dc4777557f040ed3'

def sha(data):
    return hashlib.sha256(data).hexdigest()

def save(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

def scan(root, editable):
    files = {p.relative_to(root).as_posix(): p.read_bytes() for p in root.rglob('*') if p.is_file()}
    tree = sha(''.join(k + '\0' + sha(files[k]) + '\n' for k in sorted(editable)).encode('utf-8'))
    return files, {
        'file_count': len(files),
        'editable_text_tree_sha256': tree,
        'reference_sha256': sha(files['samples/reference.py']),
        'main_header_sha256': sha(files[HEADER]),
        'files': [{'path': k, 'sha256': sha(v), 'bytes': len(v), 'editable': k in editable,
                   'utf8': _utf8(v), 'contains_crlf': b'\r\n' in v} for k, v in sorted(files.items())],
    }

def _utf8(data):
    try:
        data.decode('utf-8')
        return True
    except UnicodeDecodeError:
        return False

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-pl', type=Path, required=True, help='Existing exact 38-file PL project root')
    parser.add_argument('--destination', type=Path, required=True, help='Parent directory for NEW PL and PL-lazy directories')
    parser.add_argument('--audit-dir', type=Path, default=HERE)
    args = parser.parse_args()
    source = args.source_pl.resolve()
    destination = args.destination.resolve()
    audit = args.audit_dir.resolve()
    audit.mkdir(parents=True, exist_ok=True)
    baseline = json.loads((HERE / 'base_official_manifest.json').read_text(encoding='utf-8'))
    editable = [x['path'] for x in baseline['files'] if x['editable']]
    names = {x['path'] for x in baseline['files']}
    assert len(names) == 38 and len(editable) == 7
    for name in names:
        p = PurePosixPath(name)
        assert not p.is_absolute() and '..' not in p.parts
    source_files, source_identity = scan(source, editable)
    assert set(source_files) == names
    assert source_identity['editable_text_tree_sha256'] == EXPECTED['PL']
    assert all(sha(source_files[x['path']]) == x['sha256'] for x in baseline['files'])
    assert not (destination / 'PL').exists() and not (destination / 'PL-lazy').exists(), 'Refuse to overwrite existing snapshots'
    patch = HERE / 'lazy.patch'
    patch_bytes = patch.read_bytes()
    assert b'\r' not in patch_bytes and not patch_bytes.startswith(b'\xef\xbb\xbf')
    patch_bytes.decode('utf-8')
    for label in EXPECTED:
        target = destination / label
        target.mkdir(parents=True, exist_ok=False)
        for name in sorted(names):
            output = target / name
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_bytes(source_files[name])
    commands = []
    for extra in [['--check'], []]:
        argv = ['git', '-c', 'core.autocrlf=false', '-c', 'core.eol=lf', 'apply', *extra, str(patch)]
        completed = subprocess.run(argv, cwd=destination / 'PL-lazy', text=True, capture_output=True, encoding='utf-8')
        record = {'argv': argv, 'cwd': 'PL-lazy', 'exit_code': completed.returncode,
                  'stdout': completed.stdout, 'stderr': completed.stderr}
        commands.append(record)
        save(audit / 'patch_commands.json', commands)
        completed.check_returncode()
    identities = {}
    restored = {}
    for label in EXPECTED:
        files, identity = scan(destination / label, editable)
        assert set(files) == names
        assert identity['editable_text_tree_sha256'] == EXPECTED[label]
        assert identity['reference_sha256'] == REFERENCE
        assert all(row['utf8'] for row in identity['files'])
        identity.update(version=label, restored_from='PL 38-file base + task appendix patch' if label == 'PL-lazy' else 'PL 38-file base',
                        official_zip_sha256=None,
                        official_zip_note='No official ZIP fetched or generated by this script; reconstructed file identity only.')
        restored[label] = files
        identities[label] = identity
        save(audit / f'{label}_manifest.json', identity)
    differences = [k for k in sorted(names) if restored['PL'][k] != restored['PL-lazy'][k]]
    assert differences == [HEADER]
    assert identities['PL-lazy']['main_header_sha256'] == EXPECTED_HEADER
    assert b'\r' not in restored['PL-lazy'][HEADER]
    report = {
        'task_id': 'Q06-R003-A-LAZY-OFFICIAL', 'round_id': 'round-003', 'agent_id': 'A',
        'recorded_at': datetime.now(timezone.utc).isoformat(), 'status': 'passed',
        'base_official_manifest_sha256': sha((HERE / 'base_official_manifest.json').read_bytes()),
        'patch_sha256': sha(patch_bytes), 'patch_utf8_lf': True,
        'source_pl_all_38_matches_r002_official_manifest': True,
        'editable_paths': sorted(editable), 'code_prefix_present': False,
        'expected_tree_hashes': EXPECTED, 'actual_tree_hashes': {k: v['editable_text_tree_sha256'] for k, v in identities.items()},
        'expected_lazy_header_sha256': EXPECTED_HEADER, 'actual_lazy_header_sha256': identities['PL-lazy']['main_header_sha256'],
        'reference_sha256': REFERENCE, 'changed_paths': differences,
        'other_37_files_byte_identical': True, 'readonly_31_files_byte_identical': True,
        'git_apply_check_exit': commands[0]['exit_code'], 'git_apply_exit': commands[1]['exit_code'],
        'build_executed': False, 'npu_executed': False, 'official_contacted': False,
        'scope': 'Independent byte-level restoration; official actual submission binding is a separate parent-agent step.',
    }
    save(audit / 'restoration_audit.json', report)
    print(json.dumps({'status': 'passed', 'PL': EXPECTED['PL'], 'PL-lazy': EXPECTED['PL-lazy'], 'files_each': 38, 'other_37_equal': True}))

if __name__ == '__main__':
    main()
